#!/usr/bin/env node
// Writes src-tauri/THIRD-PARTY-LICENSES.html: the licenses of everything
// compiled into AIMtrix, which MIT, Apache, BSD and friends require shipping
// with it. Packages include it, and About AIMtrix opens it.
//
//   node dev/third-party-licenses.mjs           # regenerate
//   node dev/third-party-licenses.mjs --check   # fail if it's out of date
//
// Rust crates come from `cargo about` (install the version CI uses: cargo
// install --locked cargo-about@0.9.3 --features cli), which also refuses licenses not accepted in
// src-tauri/about.toml. npm packages are the ones a sourcemapped build shows
// ending up in the frontend.
import { execFileSync } from "node:child_process";
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = new URL("..", import.meta.url).pathname;
const out = join(root, "src-tauri/THIRD-PARTY-LICENSES.html");
const check = process.argv.includes("--check");

const run = (cmd, args) =>
  execFileSync(cmd, args, { cwd: root, encoding: "utf8", maxBuffer: 1 << 30, stdio: ["ignore", "pipe", "inherit"] });

// Rust: one entry per distinct license text, with the crates using it.
const about = JSON.parse(
  run("cargo", ["about", "generate", "--format", "json", "--manifest-path", "src-tauri/Cargo.toml", "-c", "src-tauri/about.toml"]),
);
const rust = about.licenses
  .map((l) => ({
    id: l.id,
    name: l.name,
    text: l.text.trim(),
    crates: [...new Set(l.used_by.map((u) => `${u.crate.name} ${u.crate.version}`))].sort(),
    links: Object.fromEntries(
      l.used_by.map((u) => [`${u.crate.name} ${u.crate.version}`, u.crate.repository || `https://crates.io/crates/${u.crate.name}`]),
    ),
  }))
  .sort((a, b) => a.id.localeCompare(b.id) || a.crates[0].localeCompare(b.crates[0]));

// npm: the packages whose code is in the built frontend.
run("npx", ["vite", "build", "--sourcemap", "true", "--logLevel", "error"]);
const bundled = new Set();
const walk = (dir) => {
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const path = join(dir, entry.name);
    if (entry.isDirectory()) walk(path);
    else if (path.endsWith(".js.map")) {
      for (const source of JSON.parse(readFileSync(path, "utf8")).sources) {
        const m = source.match(/node_modules\/((?:@[^/]+\/)?[^/]+)/);
        if (m) bundled.add(m[1]);
      }
    }
  }
};
walk(join(root, ".svelte-kit/output/client"));
// Rebuild without sourcemaps, so they don't end up in a package.
run("npx", ["vite", "build", "--logLevel", "error"]);
const npm = [...bundled].sort().map((name) => {
  const dir = join(root, "node_modules", name);
  const pkg = JSON.parse(readFileSync(join(dir, "package.json"), "utf8"));
  const file = readdirSync(dir).find((f) => /^(licen[cs]e|copying)/i.test(f));
  if (!file) throw new Error(`${name} has no license file`);
  return { name, version: pkg.version, license: pkg.license, text: readFileSync(join(dir, file), "utf8").trim() };
});

const esc = (s) => s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
const html = `<!doctype html>
<html lang="en">
<meta charset="utf-8">
<title>AIMtrix third-party licenses</title>
<style>
  body { font: 14px/1.4 system-ui, sans-serif; max-width: 60rem; margin: 2rem auto; padding: 0 1rem; }
  pre { white-space: pre-wrap; background: #f4f4f4; padding: 0.75rem; font-size: 12px; }
  li { margin: 0.1rem 0; }
  h3 { margin-top: 2rem; }
</style>
<h1>Third-party licenses</h1>
<p>AIMtrix is MIT licensed. It's built with the open-source software below, under the licenses shown.
Packages under the MPL-2.0 are used unmodified; their source is at the links given.
Generated by <code>dev/third-party-licenses.mjs</code>; don't edit by hand.</p>
<h2>Web interface (${npm.length} packages)</h2>
${npm
  .map((p) => `<h3>${esc(p.name)} ${esc(p.version)} (${esc(p.license)})</h3>\n<pre>${esc(p.text)}</pre>`)
  .join("\n")}
<h2>Rust crates (${new Set(rust.flatMap((l) => l.crates)).size} crates)</h2>
${rust
  .map(
    (l) => `<h3>${esc(l.name)}</h3>
<p>Used by:</p>
<ul>${l.crates.map((c) => `<li><a href="${esc(l.links[c])}">${esc(c)}</a></li>`).join("")}</ul>
<pre>${esc(l.text)}</pre>`,
  )
  .join("\n")}
</html>
`;

if (check) {
  if (!existsSync(out) || readFileSync(out, "utf8") !== html) {
    console.error("src-tauri/THIRD-PARTY-LICENSES.html is out of date: run node dev/third-party-licenses.mjs");
    process.exit(1);
  }
  console.log("THIRD-PARTY-LICENSES.html is up to date");
} else {
  writeFileSync(out, html);
  console.log(`Wrote ${out} (${npm.length} npm packages, ${rust.length} Rust license texts)`);
}
